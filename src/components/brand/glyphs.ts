/**
 * Creates a variable-width glyph while keeping row data as visual ASCII art.
 * Use `#` for filled cells and `.` for empty cells; trailing empty rows are padded.
 */
function bitmap(source: TemplateStringsArray): Glyph {
	const rows = source[0]
		.trim()
		.split("\n")
		.map((row) => row.trim().replace(/\./g, "0").replace(/#/g, "1"));

	const width = rows[0]?.length ?? 0;

	if (rows.length > ROWS) {
		throw new Error(`Glyph has ${rows.length} rows; expected at most ${ROWS}.`);
	}

	if (rows.some((row) => row.length !== width)) {
		throw new Error("Glyph rows must all have the same width.");
	}

	while (rows.length < ROWS) {
		rows.push("0".repeat(width));
	}

	return { rows, width };
}
